from datetime import datetime, timedelta, timezone
import jwt
from jwt.exceptions import InvalidTokenError
from pwdlib import PasswordHash
from pwdlib.hashers.argon2 import Argon2Hasher

from app.core.config import settings


"""Concept: How JWT Works
A JSON Web Token has 3 parts separated by dots (.): header.payload.signature
Header: Algorithm used (e.g. HS256).
Payload (Claims): Data stored inside the token:
sub: Subject identifier (the user's id or username).
role: The user's role ("USER" or "ADMIN").
exp: Expiration timestamp (when the token stops working).
Signature: Generated by hashing header + payload + SECRET_KEY.
If a user tampers with the payload (e.g. changing "role": "USER" to "role": "ADMIN"), the signature becomes invalid and our API rejects it immediately."""



# 1. Initialize Argon2 password hasher
password_hash = PasswordHash((Argon2Hasher(),))


def hash_password(password: str) -> str:
    """Hashes a raw password using Argon2."""
    return password_hash.hash(password)


def verify_password(plain_password: str, hashed_password: str) -> bool:
    """Verifies a plain password against the stored Argon2 hash."""
    return password_hash.verify(plain_password, hashed_password)


# 2. JWT Access Token Helpers
def create_access_token(
    data: dict, expires_delta: timedelta | None = None
) -> str:
    """Encodes user claims into a signed JWT token."""
    to_encode = data.copy()
    expire = datetime.now(timezone.utc) + (
        expires_delta or timedelta(minutes=settings.ACCESS_TOKEN_EXPIRE_MINUTES)
    )
    to_encode.update({"exp": expire})
    return jwt.encode(
        to_encode, settings.SECRET_KEY, algorithm=settings.ALGORITHM
    )


def decode_access_token(token: str) -> dict | None:
    """Decodes and validates a JWT token. Returns None if invalid or expired."""
    try:
        payload = jwt.decode(
            token, settings.SECRET_KEY, algorithms=[settings.ALGORITHM]
        )
        return payload
    except InvalidTokenError:
        return None